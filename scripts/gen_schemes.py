#!/usr/bin/env python3
"""Generate crates/ui-theme/src/schemes.rs from PlexusTerm's terminal themes.

Usage: python3 -I scripts/gen_schemes.py <PlexusTerm>/src/features/terminal > crates/ui-theme/src/schemes.rs

Reads themes.ts (the PlexusTerm scheme) and themes.generated.ts (iTerm2-Color-Schemes), in
TERMINAL_THEMES order, so the native list matches v0.2.15 exactly (PRD Appendix C).
"""

import pathlib
import re
import sys

ANSI = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
ANSI += ["bright" + name[0].upper() + name[1:] for name in ANSI]


def rgb(value: str) -> str:
    r, g, b = (int(value[i : i + 2], 16) for i in (1, 3, 5))
    return f"Rgb::new(0x{r:02x}, 0x{g:02x}, 0x{b:02x})"


def rgba(value: str) -> str:
    alpha = int(value[7:9], 16) if len(value) == 9 else 0xFF
    r, g, b = (int(value[i : i + 2], 16) for i in (1, 3, 5))
    return f"Rgba::new(0x{r:02x}, 0x{g:02x}, 0x{b:02x}, 0x{alpha:02x})"


def main() -> None:
    source = pathlib.Path(sys.argv[1])
    text = (source / "themes.ts").read_text() + (source / "themes.generated.ts").read_text()
    entries = re.findall(
        r'id:\s*"([^"]+)",\s*name:\s*"([^"]+)",\s*dark:\s*(true|false),\s*theme:\s*\{(.*?)\}', text, re.S
    )
    if len(entries) != 57:
        sys.exit(f"expected 57 schemes, found {len(entries)}")
    out = [
        "// Generated by scripts/gen_schemes.py from PlexusTerm v0.2.15 themes.ts and themes.generated.ts;",
        "// do not edit by hand. Palettes from iTerm2-Color-Schemes (MIT), see THIRD_PARTY_NOTICES.md.",
        "",
        "use crate::{Palette, Rgb, Rgba, Scheme};",
        "",
        "/// Every built-in scheme, in the order the Settings picker lists them (PRD Appendix C).",
        "pub static SCHEMES: [Scheme; 57] = [",
    ]
    for scheme_id, name, dark, body in entries:
        colors = dict(re.findall(r'(\w+):\s*"([^"]+)"', body))
        ansi = ", ".join(rgb(colors[key]) for key in ANSI)
        out += [
            "    Scheme {",
            f'        id: "{scheme_id}",',
            f'        name: "{name}",',
            f"        dark: {dark},",
            "        palette: Palette {",
            f"            background: {rgb(colors['background'])},",
            f"            foreground: {rgb(colors['foreground'])},",
            f"            cursor: {rgb(colors['cursor'])},",
            f"            cursor_accent: {rgb(colors['cursorAccent'])},",
            f"            selection: {rgba(colors['selectionBackground'])},",
            f"            ansi: [{ansi}],",
            "        },",
            "    },",
        ]
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
